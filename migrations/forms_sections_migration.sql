-- ============================================================
-- Adds "sections" to forms — run once in the Supabase SQL editor.
-- Purely additive: does not touch any existing table's data.
-- ============================================================

create table public.form_sections (
  section_id integer generated by default as identity primary key,
  form_id integer not null references public.forms(form_id),
  section_title text not null,
  section_description text,
  order_no integer not null default 1
);

alter table public.form_questions
  add column section_id integer references public.form_sections(section_id);
